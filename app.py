# دالة لإزالة أسماء المدرسين والأقواس بالكامل وإبقاء اسم المادة فقط
def clean_subject_name(subject_str):
    if not subject_str:
        return ""
    # حذف أي أقواس وما بداخله (مثل اسم المدرس) نهائياً
    cleaned = re.sub(r'\s*\(.*?\)', '', subject_str).strip()
    return cleaned

